def _story() -> StorySceneSpec:
    return StorySceneSpec(
        name="example",
        title="Example",
        scene="field",
        characters=("MOUSE",),
        emotions=(),
        actions=(),
        looks=(),
    )


def _scene() -> SceneSpec:
    return SceneSpec(
        name="Field",
        slug="field",
        logline="A field where the hero journeys toward shelter.",
        backgrounds=(BackgroundSpec("main", "Overgrown grassy field under golden sunlight; calm and quiet."),),
    )


